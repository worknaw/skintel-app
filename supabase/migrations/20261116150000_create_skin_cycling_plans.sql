-- A scan creates one immutable 30-day plan. Only trusted server code creates
-- or replaces plans; the mobile app may read only its owner's current plan.
create table public.skin_cycling_plans (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  source_scan_id uuid not null unique references public.skin_scans(id) on delete cascade,
  status text not null default 'active' check (status in ('active', 'replaced', 'completed')),
  start_date date not null,
  end_date date not null,
  plan_intensity text not null check (plan_intensity in ('gentle', 'balanced', 'active')),
  primary_focus text not null check (primary_focus in ('hydration', 'acne', 'redness', 'marks', 'balance')),
  ruleset_version text not null default 'skin-cycling-v1',
  created_at timestamptz not null default now(),
  check (end_date = start_date + 29)
);

create unique index skin_cycling_plans_one_active_per_user
  on public.skin_cycling_plans(user_id) where status = 'active';

create table public.skin_cycling_plan_days (
  id uuid primary key default gen_random_uuid(),
  plan_id uuid not null references public.skin_cycling_plans(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  routine_date date not null,
  day_type text not null check (day_type in ('exfoliate', 'hydrate', 'recovery', 'rest')),
  rationale text not null check (char_length(rationale) between 1 and 240),
  morning_roles text[] not null check (cardinality(morning_roles) between 1 and 6),
  evening_roles text[] not null check (cardinality(evening_roles) between 1 and 6),
  unique(plan_id, routine_date)
);

create index skin_cycling_plan_days_owner_date_idx on public.skin_cycling_plan_days(user_id, routine_date);

alter table public.skin_cycling_plans enable row level security;
alter table public.skin_cycling_plan_days enable row level security;
revoke all on public.skin_cycling_plans, public.skin_cycling_plan_days from public, anon, authenticated;
grant select on public.skin_cycling_plans, public.skin_cycling_plan_days to authenticated;
create policy skin_cycling_plans_select_own on public.skin_cycling_plans for select to authenticated
  using ((select auth.uid()) = user_id);
create policy skin_cycling_plan_days_select_own on public.skin_cycling_plan_days for select to authenticated
  using ((select auth.uid()) = user_id);

comment on table public.skin_cycling_plans is 'A non-diagnostic 30-day plan generated by trusted backend rules after a completed skin scan.';
